  // 返回 { group, extras: {name: mesh}, materials: [...] }  (材质克隆,便于受击闪红)
  function makeUnit(key) {
    const def = MODELS[key];
    const group = new THREE.Group();
    const extras = {};
    const materials = [];
    const mat = baseMat.clone();
    materials.push(mat);
    const mainMesh = new THREE.Mesh(cachedGeometry(key + '#main', def.main), mat);
    mainMesh.castShadow = true;
    group.add(mainMesh);
    if (def.extras) {
      for (const [name, ex] of Object.entries(def.extras)) {
        const em = new THREE.MeshLambertMaterial({ vertexColors: true, transparent: !!ex.transparent, opacity: ex.transparent || 1 });
        materials.push(em);
        const mesh = new THREE.Mesh(cachedGeometry(key + '#' + name, ex.boxes), em);
        mesh.castShadow = true;
        group.add(mesh);
        extras[name] = mesh;
      }
    }
    return { group, extras, materials };
  }

  // 静态场景用(共享材质,不可闪色)
  function makeStatic(key, overrides) {
    const def = typeof key === 'string' ? MODELS[key] : { main: key };
    const boxes = overrides ? def.main.concat(overrides) : def.main;
    const mesh = new THREE.Mesh(buildGeometry(boxes), baseMat);
    mesh.castShadow = true;
    return mesh;
  }

  return { buildGeometry, cachedGeometry, makeUnit, makeStatic, baseMat, MODELS };
